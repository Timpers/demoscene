"use strict";

// Bakes a .ym file into a small script the page can load, because a page opened from file:// cannot
// fetch a file next to it. The script defines YM_DEFAULT_TUNE = { name, data } (data is base64).
// Usage: node tools/ym2js.js in.ym [out.js]      (default output: tunes/default-tune.js)

const fs = require("fs");
const path = require("path");
const { parseYm } = require("../src/ymfile.js");

const [inFile, outArg] = process.argv.slice(2);
if (!inFile) { console.error("usage: ym2js.js in.ym [out.js]"); process.exit(1); }
const outFile = outArg || path.join(__dirname, "..", "tunes", "default-tune.js");

const bytes = fs.readFileSync(inFile);
const song = parseYm(bytes);            // refuse to bake a file the player cannot read
const b64 = bytes.toString("base64");
const lines = b64.match(/.{1,100}/g).map(l => `  "${l}",`).join("\n");
const text =
`// Generated by tools/ym2js.js from ${path.basename(inFile)}. Do not edit; run the tool again instead.
// ${song.title} (${song.author.trim() || "no author in the file"})
const YM_DEFAULT_TUNE = {
  name: ${JSON.stringify(path.basename(inFile))},
  data: [
${lines}
  ].join(""),
};
`;
fs.writeFileSync(outFile, text);
console.log(`${inFile} -> ${outFile}: ${bytes.length} bytes (${b64.length} as base64), "${song.title}" by "${song.author.trim()}", ` +
  `${song.format}, ${(song.frames / song.frameRate).toFixed(0)} s`);
